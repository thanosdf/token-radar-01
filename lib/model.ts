// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol
// is pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board.
//
// Implied value is calibrated against the market, not an arbitrary multiple. For every category the
// model reads the protocols that already trade, takes the median of their market-cap-to-TVL ratio,
// and prices a pre-token protocol in that category at the same ratio. A category with too few
// trading comps falls back to the whole market's median. Then growth, age and chain breadth adjust
// it, all from the snapshot's own figures:
//
//   sector multiple = median mcap / tvl of the category's trading protocols (global median when
//                     the category has fewer than four), clamped to [0.03, 1.50]
//   base            = tvl_usd x sector multiple
//   growth          = clamp(change_7d, -60, 120) per cent
//   growthMult      = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity        = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   chainMult       = 1 + min(chains - 1, 5) x 0.02
//   implied         = max(1, round(base x growthMult x maturity x chainMult))
//
// No protocol name is ever special-cased: the same function scores every row, and the sector
// multiples are derived from the snapshot at run time, never written in by hand.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

